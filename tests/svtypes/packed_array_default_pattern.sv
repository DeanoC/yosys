		c3d_idx_row  = '{0: other_row, default: row};
		c3d_idx_leaf = '{0: other_row, default: 4'h5};
		c4d_row      = '{default: row};
		c3d_cast_row = '{default: arr3x4_t'(12'h123)};
		c3d_lp_row   = '{default: ROW_LP};
		c3d_idx_lp_row = '{0: other_row, default: ROW_LP};
