	logic [1:0][2:0][3:0]  c3d_bit_def;
	logic [1:0][2:0][3:0]  c3d_fn_row;
	logic [1:0][2:0][3:0]  c3d_idx_fn_row;
	logic [1:0][2:0][3:0]  c3d_tern_row;
	logic [1:0][2:0][3:0]  c3d_idx_tern_row;
